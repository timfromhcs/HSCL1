#!/usr/bin/env python3
"""Write a hash-pinned, wheels-only requirements lock for Python 3.14 / manylinux.

    python tools/make_lock.py runtime  > requirements.lock
    python tools/make_lock.py test     > requirements-test.lock

It asks pip to *resolve* (``--dry-run --only-binary=:all:`` for cp314 manylinux) and turns
the resolver report into ``name==version --hash=sha256:...`` lines. Nothing is installed.
A package without a sha256 or without a wheel is an error: the lock never contains an
unhashed or source-built requirement.
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

RUNTIME = ["sympy==1.14.0", "numpy==2.5.4", "scipy==1.18.1", "fastapi==0.162.2",
           "uvicorn==0.54.0", "pydantic==2.14.3"]
TEST = RUNTIME + ["pytest==9.2.0", "hypothesis==6.170.15", "httpx==0.28.1"]
PLATFORMS = ["manylinux_2_28_x86_64", "manylinux2014_x86_64", "manylinux_2_17_x86_64"]


class LockError(Exception):
    pass


def lock_from_report(report: dict) -> str:
    rows = []
    for item in report["install"]:
        name = item["metadata"]["name"].lower().replace("_", "-")
        version = item["metadata"]["version"]
        info = item["download_info"]
        if not info["url"].endswith(".whl"):
            raise LockError(f"{name}: only wheels may be locked, got {info['url']}")
        digest = info.get("archive_info", {}).get("hashes", {}).get("sha256")
        if not digest:
            raise LockError(f"{name}: no sha256 in the resolver report")
        rows.append((name, version, digest))
    rows.sort()
    out = ["# Generated by tools/make_lock.py - do not edit.",
           "# Python 3.14, cp314 manylinux wheels only. Install with:",
           "#   pip install --require-hashes --only-binary=:all: -r <this file>"]
    for name, version, digest in rows:
        out.append(f"{name}=={version} --hash=sha256:{digest}")
    return "\n".join(out) + "\n"


def resolve(requirements: list[str]) -> dict:
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "report.json"
        cmd = [sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--quiet",
               "--only-binary=:all:", "--python-version", "3.14", "--implementation", "cp",
               "--abi", "cp314", "--target", str(Path(tmp) / "t"), "--report", str(report)]
        for plat in PLATFORMS:
            cmd += ["--platform", plat]
        subprocess.run(cmd + requirements, check=True, stdout=subprocess.DEVNULL)
        return json.loads(report.read_text(encoding="utf-8"))


def main(argv: list[str]) -> int:
    which = argv[1] if len(argv) > 1 else ""
    sets = {"runtime": RUNTIME, "test": TEST}
    if which not in sets:
        print("usage: make_lock.py runtime|test", file=sys.stderr)
        return 2
    sys.stdout.write(lock_from_report(resolve(sets[which])))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
