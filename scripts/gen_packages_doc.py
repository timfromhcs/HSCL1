#!/usr/bin/env python3
"""Generate docs/PACKAGES.md from the real Debian control files (plan S1, gate G12 companion).

Why generated: a hand-written package table drifts the moment a dependency changes, and a doc that
lies about what ships is a fake claim. `--check` makes the drift a red gate instead of a review note.

Usage:
    python scripts/gen_packages_doc.py            # write docs/PACKAGES.md
    python scripts/gen_packages_doc.py --check    # exit 1 if the committed file is stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PKG_DIR = ROOT / "packages/debian"
OUT = ROOT / "docs/PACKAGES.md"

HEADER = """<!-- Generated by scripts/gen_packages_doc.py - do not edit by hand. -->
# HSCL1 packages

These are the HSCL1-owned Debian packages built into the image. The table is generated from
`packages/debian/*/DEBIAN/control`, so it cannot drift from what actually ships. `hscl version`
reports the same version string that appears here.

`Version` in the control files is the development placeholder `0.0.0`; `scripts/build-deb.sh` replaces
it with the repository `VERSION` file at build time, so an installed package reports the release
version (e.g. `0.1.2~alpha.0`).

| Package | Version | Purpose | Depends |
|---|---|---|---|
"""

FOOTER = """
## Installed but not HSCL1-owned

The image also contains the Ubuntu 26.04 LTS base, KDE Plasma, and the third-party packages listed in
`distro/base/packages/`. Those are upstream packages with their own maintainers and licences; they are
not vendored or patched by HSCL1 beyond the branding overlays documented in `docs/LICENSES.md`.

## Adding or removing a package

1. Add or edit `packages/debian/<name>/DEBIAN/control`.
2. Re-run `python scripts/gen_packages_doc.py` and commit the regenerated file.
3. `python scripts/gen_packages_doc.py --check` runs in the test suite; a stale file fails the gate.
"""


def parse_control(path: Path) -> dict[str, str]:
    """Parse a Debian control file into fields (continuation lines folded, description kept split)."""
    fields: dict[str, str] = {}
    key: str | None = None
    for raw in path.read_text(encoding="utf-8").splitlines():
        if not raw.strip():
            continue
        if raw[0] in " \t" and key:
            fields[key] += "\n" + raw.strip()
            continue
        if ":" not in raw:
            continue
        name, value = raw.split(":", 1)
        key = name.strip().lower()
        fields[key] = value.strip()
    return fields


def purpose(description: str) -> str:
    """First line of Description is the synopsis; the rest is long text. Use the synopsis only."""
    first = description.splitlines()[0].strip().rstrip(".")
    return first.replace("|", "\\|")


def collect() -> list[dict[str, str]]:
    rows = []
    for control in sorted(PKG_DIR.glob("*/DEBIAN/control")):
        f = parse_control(control)
        rows.append(
            {
                "package": f.get("package", control.parent.parent.name),
                "version": f.get("version", ""),
                "purpose": purpose(f.get("description", "")),
                "depends": f.get("depends", "-").replace("|", "\\|"),
            }
        )
    return rows


def render() -> str:
    rows = collect()
    body = "".join(
        f"| `{r['package']}` | {r['version']} | {r['purpose']} | {r['depends']} |\n" for r in rows
    )
    return HEADER + body + FOOTER


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if docs/PACKAGES.md is out of date")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/PACKAGES.md is stale: run python scripts/gen_packages_doc.py", file=sys.stderr)
            return 1
        print(f"docs/PACKAGES.md is current ({len(collect())} packages)")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(collect())} packages)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
