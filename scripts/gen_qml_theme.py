#!/usr/bin/env python3
"""Generate apps/control-center/qml/Theme.qml (QML singleton) from the design tokens.

Usage: gen_qml_theme.py [--check]   --check exits 1 if the committed file is out of date.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "apps/control-center/qml/Theme.qml"


def qcolor(h: str) -> str:
    h = h.lstrip("#")
    if len(h) == 8:  # #RRGGBBAA -> Qt wants #AARRGGBB
        return f"#{h[6:8]}{h[0:6]}"
    return f"#{h}"


def camel(key: str) -> str:
    head, *rest = key.split("-")
    return head + "".join(p.capitalize() for p in rest)


def render() -> str:
    tokens = json.loads((ROOT / "themes/tokens/tokens.json").read_text(encoding="utf-8"))
    mid = tokens["themes"]["hcs-midnight"]
    lines = [
        "// GENERATED by scripts/gen_qml_theme.py from themes/tokens/tokens.json - do not edit.",
        "pragma Singleton",
        "import QtQuick",
        "",
        "QtObject {",
        '    readonly property string themeId: "hcs-midnight"',
    ]
    for k, v in mid.items():
        lines.append(f'    readonly property color {camel(k)}: "{qcolor(v)}"')
    for group in ("radius", "space"):
        for k, v in tokens[group].items():
            if isinstance(v, (int, float)):
                lines.append(f"    readonly property int {group}{k.capitalize() if not k[0].isdigit() else k}: {int(v)}")
    t = tokens["typography"]
    lines.append(f'    readonly property string fontFamily: "{t["family"].split(",")[0].strip()}"')
    for k, v in t["scale"].items():
        lines.append(f"    readonly property int font{k.capitalize()}: {v}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("Theme.qml up to date" if ok else "Theme.qml is out of date: run scripts/gen_qml_theme.py")
        return 0 if ok else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
